"""reporting_checklist: a synthetic trial report (docx) covering about a dozen CONSORT-SPI items is marked addressed
with quoted evidence, the rest missing; 'auto' chooses CONSORT-SPI for randomised text and STROBE for a cross-sectional
survey; the Word checklist is written; the result is JSON-serialisable."""
import json
from pathlib import Path

import docx
import pytest

from squipi_worker import tools  # noqa: F401
from squipi_worker.project import Project
from squipi_worker.registry import JobContext, registry, InvalidArguments
from squipi_worker.security import AllowList
from squipi_worker.tools import reporting

# Each paragraph is written to hit one checklist item and (as far as the vocabulary allows) no other.
COVERED = {
    "1a": "A cluster randomised trial of school feeding on attendance in northern Ghana",
    "2b": "The objective of the trial was to test whether daily school meals raise attendance.",
    "3a": "This was a two-arm cluster randomised trial with a 1:1 allocation ratio at the school level.",
    "4a": "Eligibility criteria: government primary schools with at least 50 pupils and no existing feeding programme were eligible.",
    "5": "The intervention consisted of a cooked midday meal on every school day for one academic year; the control group received no meals.",
    "7a": "The sample size of 80 schools was chosen to give 80% power to detect a 5 percentage-point change at the 5% level.",
    "8a": "The allocation sequence was computer-generated by the study statistician using Stata with a fixed seed.",
    "9": "Allocation was concealed from head teachers until enrolment of all schools was complete.",
    "11": "Enumerators who measured attendance were blinded to the allocation; participants could not be blinded.",
    "12a": "The primary analysis was intention-to-treat OLS of attendance on assignment with district fixed effects.",
    "13b": "Six schools were lost to follow-up because they closed during the year.",
    "17a": "Attendance was 6.1 percentage points higher in treated schools (95% CI 2.3 to 9.9), a treatment effect that is unlikely to be chance.",
    "19": "No adverse events were reported during the year.",
    "25": "The trial was funded by a grant from the Example Foundation, which had no role in the analysis.",
}


def _ctx(tmp_path):
    allow = AllowList()
    project = Project(tmp_path / "project", allow)
    return project, JobContext(project, report=lambda p, n: None, cancelled=lambda: False)


def _report(path: Path) -> Path:
    d = docx.Document()
    d.add_heading(COVERED["1a"], level=1)
    for key, sentence in COVERED.items():
        if key != "1a":
            d.add_paragraph(sentence)
    d.save(str(path))
    return path


def test_synthetic_trial_report_items_are_addressed_with_quotes_and_the_rest_missing(tmp_path):
    project, ctx = _ctx(tmp_path)
    src = _report(tmp_path / "trial-report.docx")
    project.allow.allow(src)
    doc_id = registry.call("read_document", {"path": str(src)}, ctx)["document_id"]
    out = registry.call("reporting_checklist", {"document_id": doc_id, "checklist": "auto"}, ctx)
    assert out["checklist"] == "CONSORT-SPI" and "randomisation words" in out["checklist_reason"]
    assert out["content_trust"] == "untrusted_document_data"
    rows = {r["id"]: r for r in out["table"]}
    for key, sentence in COVERED.items():
        row = rows[key]
        assert row["status"] == "addressed", (key, row)
        assert any(sentence[:40] in e["quote"] for e in row["evidence"]), (key, row["evidence"])
        for e in row["evidence"]:
            assert isinstance(e["start"], int) and e["end"] > e["start"]
    text = Path(project.document(doc_id).text_path).read_text("utf-8")
    quote = rows["9"]["evidence"][0]
    assert text[quote["start"]:quote["end"]] == quote["quote"]
    # items the report never mentions stay missing
    for key in ("3b", "6b", "7b", "14b", "23", "24", "26", "27", "28"):
        assert rows[key]["status"] == "missing", (key, rows[key])
        assert rows[key]["evidence"] == []
    assert len(COVERED) <= out["addressed"] <= len(COVERED) + 6
    assert out["missing"] >= 15 and out["coverage_pct"] == round(100 * out["addressed"] / len(out["table"]), 1)
    assert any(m.startswith("23:") and "regist" in m for m in out["missing_items"])
    assert any("CONSORT-SPI 2018" in n for n in out["notes"])
    json.dumps(out)
    # the Word checklist lists every item with its status and the missing items
    checklist = docx.Document(out["docx_path"])
    table = checklist.tables[0]
    assert len(table.rows) == len(out["table"]) + 1
    cells = {row.cells[0].text: row.cells[3].text for row in table.rows[1:]}
    assert cells["8a"] == "addressed" and cells["23"] == "missing"
    assert any("23 — Registration" in p.text for p in checklist.paragraphs)
    assert any("computer-generated" in row.cells[4].text for row in table.rows[1:])


def test_auto_picks_strobe_for_a_cross_sectional_survey_and_trend_for_quasi_experiments(tmp_path):
    project, ctx = _ctx(tmp_path)
    survey = ("Cross-sectional survey of water use in two districts. Background: prior studies report low uptake. "
              "The objective of the study was to describe household water sources. Households were randomly selected using a stratified sampling frame. "
              "Data were collected by trained enumerators with a questionnaire between March 2025 and May 2025. "
              "We adjusted for confounding by wealth and distance using logistic regression. Of 1,200 households sampled, 1,104 households completed the survey (response rate 92%). "
              "Limitations include recall bias. The findings generalise to similar rural districts. The study was funded by the Example Foundation.")
    out = registry.call("reporting_checklist", {"text": survey}, ctx)
    assert out["checklist"] == "STROBE" and "observational" in out["checklist_reason"]
    rows = {r["id"]: r for r in out["table"]}
    for key in ("1a", "3", "5", "8", "9", "13", "19", "21", "22"):
        assert rows[key]["status"] == "addressed", (key, rows[key])
    assert rows["11"]["status"] == "missing"
    assert Path(out["docx_path"]).is_file()
    json.dumps(out)
    quasi = registry.call("reporting_checklist", {"text": "We use a difference-in-differences design comparing phased roll-out districts. The intervention consisted of cash grants."}, ctx)
    assert quasi["checklist"] == "TREND" and {r["id"] for r in quasi["table"]} >= {"8", "10", "15", "22"}
    assert {r["id"]: r["status"] for r in quasi["table"]}["8"] == "addressed"
    # explicit checklist and design override win over detection
    assert registry.call("reporting_checklist", {"text": survey, "checklist": "TREND"}, ctx)["checklist"] == "TREND"
    assert registry.call("reporting_checklist", {"text": survey, "design": "randomised"}, ctx)["checklist"] == "CONSORT-SPI"
    assert registry.call("reporting_checklist", {"text": "A short note with no design words."}, ctx)["checklist_reason"].startswith("no design words")


def test_reporting_checklist_arguments_and_item_counts(tmp_path):
    project, ctx = _ctx(tmp_path)
    with pytest.raises(InvalidArguments):
        registry.call("reporting_checklist", {}, ctx)
    with pytest.raises(InvalidArguments):
        registry.call("reporting_checklist", {"text": "x", "document_id": "doc_missing"}, ctx)
    with pytest.raises(InvalidArguments):
        registry.call("reporting_checklist", {"document_id": "doc_missing"}, ctx)
    assert len(reporting.CONSORT_SPI) >= 25 and len(reporting.TREND) >= 20 and len(reporting.STROBE) >= 20
    for spec in reporting.CHECKLISTS.values():
        ids = [i["id"] for i in spec["items"]]
        assert len(ids) == len(set(ids))
        assert all(i["strong"] or i["weak"] for i in spec["items"])
